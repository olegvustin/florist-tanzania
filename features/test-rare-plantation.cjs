const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source=fs.readFileSync('features/rare-plantation.js','utf8');
let clock=1_000_000, harvested=[];
const db=new Map();
const storage={getItem:k=>db.get(k)??null,setItem:(k,v)=>db.set(k,v)};
const ctx={window:{},Date:{now:()=>clock},Number,JSON,Math,Array,Object,Error,RangeError};
vm.runInNewContext(source,ctx);
const create=ctx.window.FloristRarePlantation.create;
const p=create({storage,now:()=>clock,onHarvest:e=>harvested.push(e)});
assert.equal(p.flowers().length,3);
assert.equal(p.snapshot().plots[0].status,'empty');
p.plant(0,'rare-protea-royal');
assert.equal(p.snapshot().plots[0].status,'growing');
assert.throws(()=>p.harvest(0),/созрел/);
assert.throws(()=>p.plant(0,'rare-gloriosa-flame'),/занята/);
clock+=600_000;
assert.equal(p.snapshot().plots[0].status,'ready');
assert.equal(p.harvest(0).stock,1);
assert.equal(harvested.length,1);
assert.equal(p.snapshot().plots[0].status,'empty');
const restored=create({storage,now:()=>clock});
assert.equal(restored.snapshot().stock['rare-protea-royal'],1);
assert.equal(restored.consume('rare-protea-royal',1),0);
assert.throws(()=>restored.consume('rare-protea-royal',1),/Недостаточно/);
restored.plant(2,'rare-gloriosa-flame');
clock+=1_200_000;
assert.equal(restored.snapshot().plots[2].status,'ready');
assert.throws(()=>create({storage,now:()=>clock,onHarvest:()=>{throw Error('inventory failed')}}).harvest(2),/inventory failed/);
assert.equal(restored.snapshot().plots[2].status,'ready');
restored.reset();
assert.equal(restored.snapshot().plots[2].status,'empty');
console.log('PASS: plantation planting, maturity, harvest, persistence, inventory error, reset');
